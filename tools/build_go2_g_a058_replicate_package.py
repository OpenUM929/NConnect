def build() -> tuple[bytes, dict]:
    src = a057.source_payload()
    sentinel6 = a057.six(json.loads(src["expected_rewards.json"])["baseline"])
    shared = a057.shared_files(src)
    files: dict[str, bytes] = {"shared/" + k: v for k, v in shared.items()}
    order, rows = [], []
    for key, label, arm, seed in ROWS:
        a = arm_files(src, key, label, arm, seed, sentinel6)
        a["PACKAGE_SHA256SUMS.txt"] = a057.sums({**shared, **a})
        for k, v in a.items():
            files[f"runs/{key}/{k}"] = v
        cfg = a["run_config.env"].decode("utf-8")
        keep = re.search(r"^KEEP_DIR_NAME=(.*)$", cfg, re.M).group(1)
        zipn = re.search(r"^RESULT_ZIP_NAME=(.*)$", cfg, re.M).group(1)
        order.append(f"{key} {keep} {zipn}")
        rows.append({"key": key, "label": label, "arm": arm, "seed": seed, "rewards": weights6(arm)})
    files["sweep_order.txt"] = ("\n".join(order) + "\n").encode("utf-8")
    files["run_sweep.sh"] = LAUNCHER.read_bytes().replace(b"\r\n", b"\n")
    files["SWEEP_PLAN.json"] = (json.dumps({"work_id": WORK_ID, "rows": rows, "readout": READOUT,
                                            "proposal": PROPOSAL}, ensure_ascii=False, indent=1) + "\n").encode("utf-8")
    files["SWEEP_PLAN.md"] = plan_md(rows).encode("utf-8")
    files["SWEEP_README.txt"] = guide(None).encode("utf-8")
    files["SWEEP_SHA256SUMS.txt"] = a057.sums(dict(files))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            info = zipfile.ZipInfo(PREFIX + name, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if name.endswith(".sh") else 0o644) << 16
            z.writestr(info, files[name])
    return buf.getvalue(), {"rows": rows, "files": files, "shared": shared}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    data, info = build()
    zsha = a057.sha(data)
    print(f"arms {len(info['rows'])}, files {len(info['files'])}, zip {len(data)} bytes, sha256 {zsha}")
    if args.check:
        return 0
    UPLOAD.mkdir(parents=True, exist_ok=True)
    (UPLOAD / f"{RELEASE}.zip").write_bytes(data)
    (UPLOAD / f"{RELEASE}.zip.sha256").write_text(f"{zsha}  {RELEASE}.zip\n", encoding="utf-8", newline="\n")
    (UPLOAD / "GO2_G_A058_RUN_GUIDE.txt").write_text(guide(zsha), encoding="utf-8", newline="\n")
    print(f"published {UPLOAD / (RELEASE + '.zip')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
