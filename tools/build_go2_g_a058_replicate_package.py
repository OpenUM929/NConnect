def weights6(arm: str) -> dict[str, float]:
    w = planmod.reward_weights((planmod.KEEP / arm / "training/env.yaml").read_text(encoding="utf-8"))
    return {k: float(w[k]) for k in REWARD_NAMES}


def run_config(template: str, key: str, seed: int) -> str:
    repl = {
        "WORK_ID": WORK_ID,
        "RUN_ID": f"train_G-A058-Go2_{key}_1000",
        "EXPERIMENT_SLUG": f"go2_g_a058_{key}",
        "KEEP_DIR_NAME": f"go2_g_a058_{key}",
        "RESULT_ZIP_NAME": f"GO2_G_A058_{key.upper()}_RESULT.zip",
        "DONE_MARKER": f"'[DONE] GO2_G_A058_{key.upper()}_RESULT_READY'",
        "TMUX_NAME": f"go2_g_a058_{key}",
        "TRAIN_SEED": str(seed),
        "SINGLE_CHANGE_NAME": "train_seed",
        "SINGLE_CHANGE_FROM": "42",
        "SINGLE_CHANGE_TO": str(seed),
    }
    lines = []
    for line in template.splitlines():
        if line.startswith("# generated by"):
            lines.append("# generated by tools/build_go2_g_a058_replicate_package.py (G-A058 replicate arm); do not edit")
            continue
        m = re.match(r"^([A-Z_]+)=", line)
        if m and m.group(1) in repl:
            lines.append(f"{m.group(1)}={repl.pop(m.group(1))}")
        else:
            lines.append(line)
    if repl:
        raise ValueError(f"run_config template lacks {sorted(repl)}")
    return "\n".join(lines) + "\n"


