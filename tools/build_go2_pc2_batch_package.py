def names(work_id: str) -> dict[str, str]:
    n = pkg.names(work_id)
    n["release"] = f"GO2_{n['up']}_PC2_BATCH60_v1"
    return n


def rewards(parent_changes: dict, var: str | None = None, value: float | None = None) -> dict[str, float]:
    w = {**pkg.base6(), **EXTRA_DEFAULTS}
    w.update(parent_changes)
    if var is not None:
        w[var] = float(value)
    return w


def render(template: str, w: dict[str, float]) -> str:
    src = render_reward_source(template, {k: w[k] for k in REWARD_NAMES})
    for k, d in EXTRA_DEFAULTS.items():
        if w[k] != d:
            src = a033.add_env_reward_line(src, k, w[k])
    got = reward_dict(src)
    for k in REWARD_NAMES:
        if got.get(k) != w[k]:
            raise ValueError(f"rendered {k}={got.get(k)} != {w[k]}")
    for k, d in EXTRA_DEFAULTS.items():
        if got.get(k, d) != w[k]:
            raise ValueError(f"rendered {k} does not read back as {w[k]}")
    return src


def run_config(template: str, n: dict, key: str, var: str, frm: float, to: float) -> str:
    keep = f"go2_{n['slug']}_pc2_{key}"
    repl = {
        "WORK_ID": n["work_id"], "RUN_ID": f"train_{n['work_id']}-Go2_pc2_{key}_1000", "EXPERIMENT_SLUG": keep,
        "KEEP_DIR_NAME": keep, "RESULT_ZIP_NAME": f"GO2_{n['up']}_PC2_{key.upper()}_RESULT.zip",
        "DONE_MARKER": f"'[DONE] GO2_{n['up']}_PC2_{key.upper()}_RESULT_READY'", "TMUX_NAME": keep, "TRAIN_SEED": "42",
        "SINGLE_CHANGE_NAME": var, "SINGLE_CHANGE_FROM": f"{frm:g}", "SINGLE_CHANGE_TO": f"{to:g}",
    }
    lines = []
    for line in template.splitlines():
        if line.startswith("# generated by"):
            lines.append("# generated by tools/build_go2_pc2_batch_package.py (PC2 batch point); do not edit")
            continue
        m = re.match(r"^([A-Z_]+)=", line)
        lines.append(f"{m.group(1)}={repl.pop(m.group(1))}" if m and m.group(1) in repl else line)
    if repl:
        raise ValueError(f"run_config template lacks {sorted(repl)}")
    return "\n".join(lines) + "\n"


RUN_ALL = r"""#!/usr/bin/env bash
# PC2 일괄 실행 (generated by tools/build_go2_pc2_batch_package.py). points.txt 순서대로 run_point.sh --inner 를 부른다.
# 성능은 판단하지 않는다. 환경·패키지 오류(rc 20~25)는 같은 원인으로 남은 점도 실패하므로 멈춘다.
# 학습 뒤 오류(rc 30~34)는 기록하고 다음 점으로 간다 — 나중에 같은 'run_point.sh --only <key>' 로 재개한다.
# 이미 DONE 인 점은 run_point.sh 가 SKIP_DONE(0)으로 넘긴다. 다시 실행해도 끝난 점은 재학습하지 않는다.
set -uo pipefail
ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
LOG_DIR=${GO2_BATCH_LOG_DIR:-/workspace/_keep/__STATUS_DIR__}
mkdir -p "$LOG_DIR"
LOG="$LOG_DIR/BATCH_RUN.log"
echo "[BATCH START] $(date -Is)" | tee -a "$LOG"
worst=0
while read -r key _keep _zip; do
  [[ -z "${key:-}" ]] && continue
  echo "[BATCH POINT] $key $(date -Is)" | tee -a "$LOG"
  bash "$ROOT_DIR/run_point.sh" --inner "$key"
  rc=$?
  echo "[BATCH POINT END] $key rc=$rc $(date -Is)" | tee -a "$LOG"
  if (( rc >= 20 && rc <= 25 )); then
    echo "[BATCH STOP] environment/package error rc=$rc at $key — remaining points not started" | tee -a "$LOG"
    exit "$rc"
  fi
  (( rc != 0 && worst == 0 )) && worst=$rc
done <"$ROOT_DIR/points.txt"
echo "[BATCH END] $(date -Is) worst_rc=$worst" | tee -a "$LOG"
exit "$worst"
"""


def point_files(n: dict, src: dict, key: str, parent_changes: dict, var: str, value: float,
                exemption: str | None, note: str) -> tuple[dict[str, bytes], str]:
    # 같은 회차 자신의 회수 결과(원장 행·_keep 폴더)는 이력이 아니다 — 발행 뒤 재빌드가 자기 결과에 막히지 않게.
    own = (f"| {n['work_id']} ", f"_keep/go2_{n['slug']}_pc2_{key}")
    hits = [h for h in tb.history_conflicts(var, value) if not any(o in h for o in own)]
    if hits and not exemption:
        raise ValueError(f"{key}: {var}={value} 시험 이력 있음 — 제외 대상: {hits}")
    sentinel6 = a057.six(json.loads(src["expected_rewards.json"])["baseline"])
    parent_w, cand_w = rewards(parent_changes), rewards(parent_changes, var, value)
    diff = [k for k in TERMS if cand_w[k] != parent_w[k]]
    repeat = bool(exemption and exemption.startswith("REPEAT:")) and diff == []  # 부모 그대로 재학습(학습 흔들림 측정)
    if diff != [var] and not repeat:
        raise ValueError(f"{key}: must change exactly {var}, changed {diff}")
    template = src["candidate/quadruped_rewards.py"].decode("utf-8")
    cand_src, parent_src = render(template, cand_w), render(template, parent_w)
    parent_label = "P0" if not parent_changes else PARENT_LABEL
    experiment = {
        "schema": "go2_pc2_batch_point_v1", "work_id": n["work_id"], "device": "PC2", "run_key": key,
        "design": DESIGN, "promotion": "forbidden_pc_exploration",
        "parent": {"label": parent_label, "rewards": parent_w,
                   "harvest_for_readout": P0_HARVEST if parent_label == "P0"
                   else (PARENT_HARVEST or f"workspace/_keep/go2_{n['slug']}_pc2_q0_lin_vel_z_l2_m1p5 (같은 일괄 실행의 Q0)")},
        "single_change": {"name": var, "from": parent_w[var], "to": value}, "rewards": cand_w,
        "history_check": (f"이력 예외: {exemption}; 이력 {hits}" if exemption else "같은 항·같은 값 시험 이력 없음"),
        "note": note,
        "training": {"seed": 42, "num_envs": 4096, "max_iterations": 1000, "from_scratch": True},
        "evaluation": {"checkpoint_iter": 900, "seeds": [101, 202, 303], "case_count": 69},
    }
    expected_cand = {k: cand_w[k] for k in REWARD_NAMES}
    expected_cand.update({k: cand_w[k] for k in EXTRA_DEFAULTS})
    arm = {
        "candidate/quadruped_rewards.py": cand_src.encode("utf-8"),
        "reference/baseline_quadruped_rewards.py": parent_src.encode("utf-8"),
        "reference/reward_base_quadruped_rewards.py": parent_src.encode("utf-8"),
        "expected_rewards.json": (json.dumps({"baseline": sentinel6, "candidate": expected_cand}, indent=2) + "\n").encode("utf-8"),
        "run_config.env": run_config(src["run_config.env"].decode("utf-8"), n, key, var, parent_w[var], value).encode("utf-8"),
        "experiment.json": (json.dumps(experiment, ensure_ascii=False, indent=1) + "\n").encode("utf-8"),
        "README.txt": (f"{n['work_id']} PC2 batch point {key}: 부모 {parent_label} 위 {var} {parent_w[var]:g} -> {value:g}. "
                       f"{note}\n이 폴더는 run_point.sh 가 펼쳐서 쓴다. PC 결과는 탐색용이며 제출 후보가 아니다.\n").encode("utf-8"),
    }
    cfg = arm["run_config.env"].decode("utf-8")
    keep = re.search(r"^KEEP_DIR_NAME=(.*)$", cfg, re.M).group(1)
    zipn = re.search(r"^RESULT_ZIP_NAME=(.*)$", cfg, re.M).group(1)
    return arm, f"{key} {keep} {zipn}"


def build(work_id: str = PROVISIONAL_WORK_ID) -> tuple[bytes, dict]:
    n = names(work_id)
    src = a057.source_payload()
    shared = a057.shared_files(src)
    files: dict[str, bytes] = {"shared/" + k: v for k, v in shared.items()}
    lines = []
    for key, pc, var, value, exemption, note in POINTS:
        arm, line = point_files(n, src, key, pc, var, value, exemption, note)
        arm["PACKAGE_SHA256SUMS.txt"] = a057.sums({**shared, **arm})
        files.update({f"runs/{key}/{k}": v for k, v in arm.items()})
        lines.append(line)
    files["points.txt"] = ("\n".join(lines) + "\n").encode("utf-8")
    files["point_config.env"] = (f"POINT_WORK_ID={n['work_id']}\nPOINT_STATUS_DIR_NAME={n['status_dir']}\n"
                                 f"POINT_WORK_DIR={n['work_dir']}\nPOINT_TMUX_NAME={n['tmux']}\n").encode("utf-8")
    files["run_point.sh"] = pkg.LAUNCHER.read_bytes().replace(b"\r\n", b"\n")
    files["run_all.sh"] = RUN_ALL.replace("__STATUS_DIR__", n["status_dir"]).encode("utf-8")
    files["README.txt"] = guide(n, None).encode("utf-8")
    files["SHA256SUMS.txt"] = a057.sums(dict(files))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            info = zipfile.ZipInfo(n["prefix"] + name, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if name.endswith(".sh") else 0o644) << 16
            z.writestr(info, files[name])
    return buf.getvalue(), {"names": n, "files": files}


def guide(n: dict, zip_sha: str | None) -> str:
    pts = "\n".join(f"   {i}. {k:32s} 부모 {'P0' if not pc else 'Q0'}  {v} -> {x:g}" for i, (k, pc, v, x, _, _) in enumerate(POINTS, 1))
    return f"""GO2 {n['work_id']} PC2 일괄 실행 — 60점 목표 전략 {len(POINTS)}점 (설계 {DESIGN})
==================================================
점(실행 순서). P0 = PC2 A048(G-A060 B1), Q0 = P0 + lin_vel_z -1.5(A043 보상, 1번 점):
{pts}
점마다 학습 seed 42, 4096 env, 1000 iter, 평가 iter 900, 69 case, 영상 10편. 점당 약 2시간 25분 [추정].

1. 올리기: {n['release']}.zip  SHA256 {zip_sha or '(발행 시 기록)'}  → /workspace/{n['release']}.zip
2. 환경 변수: workspace/_keep/go2_g_a060_pc2_run_chain.sh 머리의 mount·export 줄을 먼저 실행한다.
3. 실행(한 줄, nohup 또는 tmux 안에서):
   unzip -oq /workspace/{n['release']}.zip -d /workspace && bash /workspace/{n['prefix']}run_all.sh
   진행: /workspace/_keep/{n['status_dir']}/BATCH_RUN.log, POINT_STATUS.tsv
4. GPU 감시: tools/go2_gpu_watch.sh --hours 18 --pattern 'go2_{n['slug']}_pc2_*' (패턴 필수, 감시는 기록만 한다)
5. 실패 처리: rc 20~25(환경·패키지)면 run_all 이 멈춘다 — 고친 뒤 같은 한 줄(끝난 점은 SKIP).
   rc 30~34(학습 뒤)는 다음 점으로 간다 — 끝난 뒤 'bash run_point.sh --only <key>' 로 그 점만 재개한다.
   학습 도중 실패(iter 900 checkpoint 없음)는 자동 재학습하지 않는다 — 보고한다.
6. 회수: 점마다 /workspace/_keep/go2_{n['slug']}_pc2_<key>/ 폴더와 GO2_{n['up']}_PC2_<KEY>_RESULT.zip + .sha256,
   /workspace/_keep/{n['status_dir']}/ → 저장소 workspace/_keep/ (100MB 초과는 95MB parts).
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--publish", action="store_true")
    ap.add_argument("--work-id")
    a = ap.parse_args(argv)
    work_id = a.work_id or PROVISIONAL_WORK_ID
    data, info = build(work_id)
    sha = hashlib.sha256(data).hexdigest()
    n = info["names"]
    print(f"work id {work_id}{'' if a.work_id else ' (provisional)'} points {len(POINTS)} files {len(info['files'])} "
          f"zip {len(data)} bytes sha256 {sha}")
    if a.publish:
        if not a.work_id:
            print("--publish needs --work-id")
            return 64
        out = GO2 / "upload" / work_id / "current"
        out.mkdir(parents=True, exist_ok=True)
        z = out / f"{n['release']}.zip"
        if z.exists():
            print(f"refuse to overwrite {z}")
            return 65
        z.write_bytes(data)
        (out / f"{n['release']}.zip.sha256").write_text(f"{sha}  {z.name}\n", encoding="utf-8", newline="\n")
        (out / f"{n['release']}_RUN_GUIDE.txt").write_text(guide(n, sha), encoding="utf-8", newline="\n")
        print(f"published {z}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
