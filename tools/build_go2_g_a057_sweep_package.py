FIXED_TIME = (2026, 9, 29, 0, 0, 0)


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def source_payload() -> dict[str, bytes]:
    z = zipfile.ZipFile(planmod.SOURCE_PACKAGE)
    out = {}
    for info in z.infolist():
        if info.is_dir():
            continue
        name = info.filename[len(planmod.SOURCE_PREFIX):]
        out[name] = z.read(info)
    return out


def six(weights: dict) -> dict[str, float]:
    return {k: float(weights[k]) for k in REWARD_NAMES}


def run_config(template: str, key: str, row: dict, base6: dict) -> str:
    name, value = row["variable"], float(row["value"])
    repl = {
        "WORK_ID": "G-A057",
        "RUN_ID": f"train_G-A057-Go2_a048_{key}_1000",
        "EXPERIMENT_SLUG": f"go2_g_a057_{key}",
        "KEEP_DIR_NAME": f"go2_g_a057_{key}",
        "RESULT_ZIP_NAME": f"GO2_G_A057_{key.upper()}_RESULT.zip",
        "DONE_MARKER": f"'[DONE] GO2_G_A057_{key.upper()}_RESULT_READY'",
        "TMUX_NAME": f"go2_g_a057_{key}",
        "SINGLE_CHANGE_NAME": name,
        "SINGLE_CHANGE_FROM": f"{base6[name]:g}",
        "SINGLE_CHANGE_TO": f"{value:g}",
    }
    lines = []
    for line in template.splitlines():
        if line.startswith("# generated by"):
            lines.append("# generated by tools/build_go2_g_a057_sweep_package.py (G-A057 sweep arm); do not edit")
            continue
        m = re.match(r"^([A-Z_]+)=", line)
        if m and m.group(1) in repl:
            lines.append(f"{m.group(1)}={repl.pop(m.group(1))}")
        else:
            lines.append(line)
    if repl:
        raise ValueError(f"run_config template lacks {sorted(repl)}")
    return "\n".join(lines) + "\n"


def arm_files(src: dict[str, bytes], row: dict, base6: dict, sentinel6: dict, prereg_sha: str) -> dict[str, bytes]:
    key, name, value = row["key"], row["variable"], float(row["value"])
    cand6 = dict(base6)
    cand6[name] = value
    changed = [k for k in REWARD_NAMES if cand6[k] != base6[k]]
    if changed != [name]:
        raise ValueError(f"{key}: must change exactly {name}, changed {changed}")
    if cand6 != six(row["rewards"]):
        raise ValueError(f"{key}: plan rewards {row['rewards']} differ from rendered {cand6}")
    template = src["candidate/quadruped_rewards.py"].decode("utf-8")
    cand_src = render_reward_source(template, cand6)
    base_src = render_reward_source(template, base6)
    if reward_dict(cand_src) != cand6 or reward_dict(base_src) != base6:
        raise ValueError(f"{key}: rendered reward file does not parse back")
    expected = {"baseline": sentinel6, "candidate": cand6}
    experiment = {
        "schema": "go2_sweep_arm_v1", "work_id": "G-A057", "run_key": key,
        "purpose": "보상 변수별 값 변화에 따른 행동·성능 반응 데이터 수집. 개선을 전제하지 않는다. 채택·승급·공식 제출 판정 대상 아님.",
        "promotion": "forbidden_sweep_data_only",
        "reward_base": {"label": planmod.BASE_LABEL, "arm": planmod.BASE_ARM, "rewards": base6},
        "single_change": {"name": name, "from": base6[name], "to": value},
        "rewards": cand6,
        "training": {"seed": 42, "num_envs": 4096, "max_iterations": 1000, "from_scratch": True},
        "evaluation": {"checkpoint_iter": 900, "seeds": [101, 202, 303], "case_count": 69,
                       "sentinel": "G-A033 stored arm, 5 cases (runner default)"},
        "runner": f"{RUNNER} from upload/G-A055/current (v2) bytes unchanged, --inner, GO2_STAGE=full",
        "plan_row": row,
        "preregistration": {"path": "go2_g_a057/PREREGISTRATION.json", "sha256": prereg_sha, "row": key,
                            "reader": "tools/go2_g_a057_prereg_readout.py"},
    }
    readme = (f"G-A057 sweep arm {key}\n"
              f"A048 보상에서 {name} 한 항만 {base6[name]:g} -> {value:g}. 학습 seed 42, 4096 env, 1000 iter, 평가 iter 900, 69 case.\n"
              "이 폴더는 run_sweep.sh 가 펼쳐서 쓴다. 혼자 실행하지 않는다. 결과는 반응 데이터이며 채택·승급 대상이 아니다.\n")
    files = {
        "candidate/quadruped_rewards.py": cand_src.encode("utf-8"),
        "reference/baseline_quadruped_rewards.py": base_src.encode("utf-8"),
        "reference/reward_base_quadruped_rewards.py": base_src.encode("utf-8"),
        "expected_rewards.json": (json.dumps(expected, indent=2) + "\n").encode("utf-8"),
        "run_config.env": run_config(src["run_config.env"].decode("utf-8"), key, row, base6).encode("utf-8"),
        "experiment.json": (json.dumps(experiment, ensure_ascii=False, indent=1) + "\n").encode("utf-8"),
        "README.txt": readme.encode("utf-8"),
    }
    return files


def shared_files(src: dict[str, bytes]) -> dict[str, bytes]:
    return {k: v for k, v in src.items() if k not in OVERLAY}


def sums(files: dict[str, bytes]) -> bytes:
    return "".join(f"{sha(files[k])}  {k}\n" for k in sorted(files)).encode("utf-8")


