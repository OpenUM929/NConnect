def build() -> tuple[bytes, dict]:
    plan = planmod.plan()
    src = source_payload()
    base6 = six(plan["base_env_rewards"])
    sentinel6 = six(json.loads(src["expected_rewards.json"])["baseline"])
    new_rows = [r for r in plan["runs"] if r["status"] == "NEW_TRAIN"]
    if any(r["status"] == "EVAL_ONLY" for r in plan["runs"]):
        raise ValueError("EVAL_ONLY rows need a manual evaluation path; not packaged automatically")
    shared = shared_files(src)
    files: dict[str, bytes] = {}
    for k, v in shared.items():
        files["shared/" + k] = v
    order = []
    prereg = PREREG_JSON.read_bytes().replace(b"\r\n", b"\n")
    pre = json.loads(prereg)
    if sorted(pre["rows"]) != sorted(r["key"] for r in new_rows):
        raise ValueError("PREREGISTRATION rows differ from the NEW_TRAIN rows")
    files["PREREGISTRATION.json"] = prereg
    files["PREREGISTRATION.md"] = PREREG_MD.read_bytes().replace(b"\r\n", b"\n")
    for row in new_rows:
        arm = arm_files(src, row, base6, sentinel6, sha(prereg))
        tree = {**shared, **arm}
        arm["PACKAGE_SHA256SUMS.txt"] = sums(tree)
        for k, v in arm.items():
            files[f"runs/{row['key']}/{k}"] = v
        cfg = arm["run_config.env"].decode("utf-8")
        keep = re.search(r"^KEEP_DIR_NAME=(.*)$", cfg, re.M).group(1)
        zipn = re.search(r"^RESULT_ZIP_NAME=(.*)$", cfg, re.M).group(1)
        order.append(f"{row['key']} {keep} {zipn}")
    files["sweep_order.txt"] = ("\n".join(order) + "\n").encode("utf-8")
    files["run_sweep.sh"] = LAUNCHER.read_bytes().replace(b"\r\n", b"\n")
    files["SWEEP_PLAN.json"] = (json.dumps(plan, ensure_ascii=False, indent=1) + "\n").encode("utf-8")
    files["SWEEP_PLAN.md"] = planmod.markdown(plan).encode("utf-8")
    files["SWEEP_README.txt"] = guide(new_rows, None).encode("utf-8")
    files["SWEEP_SHA256SUMS.txt"] = sums({k: v for k, v in files.items()})
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            info = zipfile.ZipInfo(PREFIX + name, FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if name.endswith(".sh") else 0o644) << 16
            z.writestr(info, files[name])
    return buf.getvalue(), {"plan": plan, "new_rows": new_rows, "files": files}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    data, info = build()
    zsha = sha(data)
    print(f"arms {len(info['new_rows'])}, files {len(info['files'])}, zip {len(data)} bytes, sha256 {zsha}")
    if args.check:
        return 0
    UPLOAD.mkdir(parents=True, exist_ok=True)
    (UPLOAD / f"{RELEASE}.zip").write_bytes(data)
    (UPLOAD / f"{RELEASE}.zip.sha256").write_text(f"{zsha}  {RELEASE}.zip\n", encoding="utf-8", newline="\n")
    (UPLOAD / "GO2_G_A057_RUN_GUIDE.txt").write_text(guide(info["new_rows"], zsha), encoding="utf-8", newline="\n")
    print(f"published {UPLOAD / (RELEASE + '.zip')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
